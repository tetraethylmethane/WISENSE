"""Full-integer quantisation and firmware sources.

The paper deploys "full unsigned 8-bit" models: uint8 at the input and
output, int8 inside (TFLite has no uint8 kernels any more; the converter
inserts the boundary quantize ops). Calibration uses training-subject
samples only. Test vectors use the device's own selection rule
(features.select: most variable of the 47 good subcarriers).

Writes, next to the model:
    model_uint8.tflite
and into firmware/esp32s3_har/main/generated/:
    model_data.cc / .h     the flatbuffer as an aligned C array
    model_ops.h            exactly the ops this model uses, as resolver calls
    test_vectors.h         N quantised test-subject inputs + labels, for the
                           on-device accuracy and latency benchmark

model_ops.h is generated rather than hand-written because the unrolled LSTM
lowers to a long op list that changes with the converter version; a missing
op only shows up as a failed AllocateTensors() on the board.

    python -m wisense.export artifacts/small
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from wisense.data import ROOT, load
from wisense.features import per_subcarrier, select

GENERATED = ROOT / "firmware" / "esp32s3_har" / "main" / "generated"
N_CALIBRATION = 300
N_TEST_VECTORS = 25          # 5 per class; ~21 KB of flash

# TFLite builtin op name -> tflite::MicroMutableOpResolver method.
RESOLVER = {
    "ADD": "AddAdd", "AVERAGE_POOL_2D": "AddAveragePool2D",
    "CONCATENATION": "AddConcatenation", "CONV_2D": "AddConv2D",
    "DEPTHWISE_CONV_2D": "AddDepthwiseConv2D", "DEQUANTIZE": "AddDequantize",
    "EXPAND_DIMS": "AddExpandDims", "FULLY_CONNECTED": "AddFullyConnected",
    "GATHER": "AddGather", "LOGISTIC": "AddLogistic", "MAX_POOL_2D": "AddMaxPool2D",
    "MEAN": "AddMean", "MUL": "AddMul", "PACK": "AddPack", "PAD": "AddPad",
    "QUANTIZE": "AddQuantize", "RELU": "AddRelu", "RESHAPE": "AddReshape",
    "SHAPE": "AddShape", "SLICE": "AddSlice", "SOFTMAX": "AddSoftmax",
    "SPLIT": "AddSplit", "SPLIT_V": "AddSplitV", "SQUEEZE": "AddSqueeze",
    "STRIDED_SLICE": "AddStridedSlice", "SUB": "AddSub", "TANH": "AddTanh",
    "TRANSPOSE": "AddTranspose", "UNPACK": "AddUnpack",
    "UNIDIRECTIONAL_SEQUENCE_LSTM": "AddUnidirectionalSequenceLSTM",
    "BATCH_MATMUL": "AddBatchMatMul",
    "FILL": "AddFill",              # the LSTM's zero initial state
    "ZEROS_LIKE": "AddZerosLike", "CAST": "AddCast", "SUM": "AddSum",
    "MAXIMUM": "AddMaximum", "MINIMUM": "AddMinimum", "RELU6": "AddRelu6",
    "BROADCAST_TO": "AddBroadcastTo", "SELECT_V2": "AddSelectV2",
}


def quantise(model, calibration: np.ndarray) -> bytes:
    import tensorflow as tf

    def rep():
        for s in calibration:
            yield [s[None].astype(np.float32)]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.uint8
    conv.inference_output_type = tf.uint8
    return conv.convert()


def op_names(tflite: bytes) -> list[str]:
    import tensorflow as tf
    interp = tf.lite.Interpreter(model_content=tflite)
    return sorted({op["op_name"] for op in interp._get_ops_details()})


def quantise_input(x: np.ndarray, scale: float, zero: int) -> np.ndarray:
    return np.clip(np.round(x / scale + zero), 0, 255).astype(np.uint8)


def _c_bytes(data: bytes, per_line: int = 16) -> str:
    rows = (", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) for i in range(0, len(data), per_line))
    return ",\n    ".join(rows)


def write_firmware_sources(tflite: bytes, test_x: np.ndarray, test_y: np.ndarray, out: Path = GENERATED) -> None:
    import tensorflow as tf

    out.mkdir(parents=True, exist_ok=True)
    banner = "// Generated by `python -m wisense.export`. Do not edit.\n"

    (out / "model_data.h").write_text(
        banner + "#pragma once\n#include <cstddef>\n\n"
        "extern const unsigned char g_model_data[];\nextern const size_t g_model_data_len;\n")
    (out / "model_data.cc").write_text(
        banner + '#include "model_data.h"\n\n'
        "alignas(16) const unsigned char g_model_data[] = {\n    " + _c_bytes(tflite)
        + f"\n}};\nconst size_t g_model_data_len = {len(tflite)};\n")

    ops = op_names(tflite)
    missing = [o for o in ops if o not in RESOLVER]
    if missing:
        raise RuntimeError(f"no resolver mapping for ops {missing}; add them to RESOLVER")
    (out / "model_ops.h").write_text(
        banner + "#pragma once\n#include \"tensorflow/lite/micro/micro_mutable_op_resolver.h\"\n\n"
        f"constexpr int kNumModelOps = {len(ops)};\n"
        "using ModelOpResolver = tflite::MicroMutableOpResolver<kNumModelOps>;\n\n"
        "inline TfLiteStatus RegisterModelOps(ModelOpResolver &r) {\n"
        + "".join(f"    if (r.{RESOLVER[o]}() != kTfLiteOk) return kTfLiteError;  // {o}\n" for o in ops)
        + "    return kTfLiteOk;\n}\n")

    interp = tf.lite.Interpreter(model_content=tflite)
    scale, zero = interp.get_input_details()[0]["quantization"]
    q = quantise_input(test_x, scale, zero)
    body = ",\n".join("  {" + ", ".join(str(int(v)) for v in row) + "}" for row in q)
    (out / "test_vectors.h").write_text(
        banner + "#pragma once\n#include <cstdint>\n\n"
        "// Held-out-subject recordings, already in the model's uint8 input domain.\n"
        f"// Input quantisation: real = {scale!r} * (q - {zero}).\n"
        f"constexpr int kNumTestVectors = {len(q)};\nconstexpr int kTestVectorLen = {q.shape[1]};\n"
        f"constexpr float kInputScale = {scale!r}f;\nconstexpr int kInputZeroPoint = {int(zero)};\n"
        f"static const uint8_t kTestLabels[kNumTestVectors] = {{{', '.join(str(int(v)) for v in test_y)}}};\n"
        f"static const uint8_t kTestVectors[kNumTestVectors][kTestVectorLen] = {{\n{body}\n}};\n")
    print(f"wrote {out} ({len(tflite):,} B model, {len(ops)} op types: {' '.join(ops)})")


def main() -> None:
    from tensorflow import keras

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("run", type=Path, help="training run directory containing model.keras")
    ap.add_argument("--no-firmware", action="store_true")
    args = ap.parse_args()

    model = keras.models.load_model(args.run / "model.keras")
    trn, tst = load().split()
    rng = np.random.default_rng(0)
    xtr = per_subcarrier(trn.x)
    tflite = quantise(model, xtr[rng.choice(len(xtr), N_CALIBRATION, replace=False)][..., None])
    (args.run / "model_uint8.tflite").write_bytes(tflite)
    print(f"saved {args.run / 'model_uint8.tflite'} ({len(tflite):,} B)")

    if not args.no_firmware:
        per = N_TEST_VECTORS // 5
        idx = np.concatenate([rng.choice(np.flatnonzero(tst.y == c), per, replace=False) for c in range(5)])
        write_firmware_sources(tflite, select(tst.x[idx]), tst.y[idx])


if __name__ == "__main__":
    main()
