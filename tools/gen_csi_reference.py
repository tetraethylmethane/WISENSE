"""Freeze host preprocessing outputs for firmware/tests/test_csi_dsp.c.

Takes one held-out recording, pushes 900 packets (so the 850-row ring wraps
by 50), and records what wisense.csi / wisense.features produce for the
window: per-packet amplitude, the selected subcarrier (most variable of the
47 good ones), and the extracted
series. The C test feeds the same raw bytes through csi_dsp.c and must agree.

    python -m tools.gen_csi_reference
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from wisense.csi import KEPT_SUBCARRIERS, TIMESTEPS, amplitude, preprocess, read_raw
from wisense.features import top_variance_index
from wisense.data import TEST_SUBJECTS, index

OUT = Path(__file__).resolve().parents[1] / "firmware" / "tests" / "csi_reference.h"
N_PUSH = 900
SCALE, ZERO = 0.125, 3   # arbitrary but exercises rounding and the upper clamp


def main() -> None:
    rec = next(r for r in index() if r.subject == TEST_SUBJECTS[0] and r.activity == "WA")
    _, csi = read_raw(rec.path)
    raw = csi[:N_PUSH].astype(np.int8)
    amp = preprocess(raw[N_PUSH - TIMESTEPS:])                  # the window after wrap
    sc = int(top_variance_index(amp[None])[0])   # index into the 52, from the good 47
    series = amp[:, sc].astype(np.float32)
    q = np.clip(np.round(series.astype(np.float64) / SCALE + ZERO), 0, 255).astype(np.uint8)
    amp0 = amplitude(raw[:1])[0, list(KEPT_SUBCARRIERS)]

    def arr(a, fmt):
        return ", ".join(fmt(v) for v in a)

    rows = ",\n".join("    {" + arr(r, str) + "}" for r in raw)
    OUT.write_text(
        "/* Generated by `python -m tools.gen_csi_reference` from\n"
        f" * {rec.path.name} ({rec.activity}, {rec.subject}). Do not edit. */\n"
        "#ifndef CSI_REFERENCE_H\n#define CSI_REFERENCE_H\n#include <stdint.h>\n\n"
        f"#define REF_N_PUSH {N_PUSH}\n#define REF_SELECTED_SC {sc}u\n"
        f"#define REF_SCALE {SCALE}f\n#define REF_ZERO {ZERO}\n\n"
        f"static const int8_t ref_raw[REF_N_PUSH][128] = {{\n{rows}\n}};\n\n"
        f"static const float ref_amp0[52] = {{{arr(amp0, lambda v: f'{float(v)!r}f')}}};\n\n"
        f"static const float ref_series[{TIMESTEPS}] = {{{arr(series, lambda v: f'{float(v)!r}f')}}};\n\n"
        f"static const uint8_t ref_quant[{TIMESTEPS}] = {{{arr(q, str)}}};\n\n"
        "#endif\n")
    print(f"wrote {OUT}: selected kept subcarrier {sc} (raw {KEPT_SUBCARRIERS[sc]})")


if __name__ == "__main__":
    main()
